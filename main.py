#Funções  
def calcula_soma(x,y):
  return x + y

def calcula_subtração(x,y):
  return x - y

def calcula_multiplicação(x,y):
  return x * y

def calcula_divisão(x,y):
  return x / y

def calcula_resto(x,y):
  return x % y

def calcula_percentual(x,y):
  return x / 100 * y 

def calcula_potenciacao(x,y):
  return x**y

def calcula_radiciacao(x,y):
  return x**(1/y)